/** Games the signed-in player is in that are still live (for "resume" on the home screen). */
export async function fetchMyLiveGames(): Promise<GameRow[]> {
  const { data, error } = await supabase
    .from('games')
    .select('*')
    .in('status', ['LOBBY', 'COUNTDOWN', 'ACTIVE'])
    .order('created_at', { ascending: false });
  if (error) throw new Error(error.message);
  return (data ?? []) as GameRow[];
}

export async function updateDisplayName(userId: string, name: string): Promise<void> {
  const { error } = await supabase.from('profiles').update({ display_name: name }).eq('id', userId);
  if (error) throw new Error(error.message);
}

export type { RealtimeChannelStatus };
type RealtimeChannelStatus = 'SUBSCRIBED' | 'TIMED_OUT' | 'CLOSED' | 'CHANNEL_ERROR';

/** Calls `onChange` on any change to the game, its players, snapshots, tags or events; `onStatus` on channel state. */
export function subscribeToGame(
  gameId: string,
  onChange: () => void,
  onStatus?: (s: RealtimeChannelStatus) => void,
): () => void {
  const filter = `game_id=eq.${gameId}`;
  const channel = supabase
    .channel(`game:${gameId}:${Math.random().toString(36).slice(2, 8)}`)
    .on('postgres_changes', { event: '*', schema: 'manhunt', table: 'games', filter: `id=eq.${gameId}` }, onChange)
    .on('postgres_changes', { event: '*', schema: 'manhunt', table: 'game_players', filter }, onChange)
    .on('postgres_changes', { event: 'INSERT', schema: 'manhunt', table: 'location_snapshots', filter }, onChange)
    .on('postgres_changes', { event: '*', schema: 'manhunt', table: 'tag_requests', filter }, onChange)
    .on('postgres_changes', { event: 'INSERT', schema: 'manhunt', table: 'game_events', filter }, onChange)
    .subscribe((s) => onStatus?.(s as RealtimeChannelStatus));
  return () => {
    void supabase.removeChannel(channel);
  };
}
