// Every write goes through a server RPC; the client never writes tables directly.
async function rpc<T>(fn: string, args?: Record<string, unknown>): Promise<T> {
  const { data, error } = await supabase.rpc(fn, args);
  if (error) throw new Error(error.message);
  return data as T;
}

export interface CreateGameInput {
  lat: number;
  lng: number;
  radiusM: number;
  durationS?: number;
  headStartS?: number;
  snapshotIntervalS?: number;
}

export const createGame = (i: CreateGameInput) =>
  rpc<GameRow>('create_game', {
    p_lat: i.lat,
    p_lng: i.lng,
    p_radius_m: i.radiusM,
    p_duration_s: i.durationS ?? null,
    p_head_start_s: i.headStartS ?? null,
    p_snapshot_interval_s: i.snapshotIntervalS ?? null,
  });
export const joinGame = (code: string) => rpc<GameRow>('join_game', { p_code: code.trim().toUpperCase() });
export const leaveGame = (gameId: string) => rpc<GameRow>('leave_game', { p_game_id: gameId });
export const assignTeams = (gameId: string) => rpc<GameRow>('assign_teams', { p_game_id: gameId });
export const setPlayerRole = (gameId: string, playerId: string, role: Role) =>
  rpc<GameRow>('set_player_role', { p_game_id: gameId, p_player_id: playerId, p_role: role });
export const startGame = (gameId: string) => rpc<GameRow>('start_game', { p_game_id: gameId });
export const cancelGame = (gameId: string) => rpc<GameRow>('cancel_game', { p_game_id: gameId });
export const advanceGame = (gameId: string) => rpc<GameRow>('advance_game', { p_game_id: gameId });

export interface LocationReading {
  lat: number;
  lng: number;
  accuracyM: number;
  /** Device time of the fix. */
  recordedAt: Date | string;
  isMocked?: boolean;
}
/** Resolves true when the server stored the reading (only while ACTIVE, from ACTIVE players). */
export const recordLocation = (gameId: string, r: LocationReading) =>
  rpc<boolean>('record_location', {
    p_game_id: gameId,
    p_lat: r.lat,
    p_lng: r.lng,
    p_accuracy_m: r.accuracyM,
    p_recorded_at: typeof r.recordedAt === 'string' ? r.recordedAt : r.recordedAt.toISOString(),
    p_is_mocked: r.isMocked ?? false,
  });

